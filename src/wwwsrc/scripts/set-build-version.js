// Stamps src/app/build-info.ts with the app version (from package.json) and
// the current build time before each build, so the WebXR player UI can
// display which build is running.
const fs = require('fs');
const path = require('path');

const pkg = require(path.join(__dirname, '..', 'package.json'));
const stamp = new Date().toISOString().replace('T', ' ').slice(0, 16); // "YYYY-MM-DD HH:MM"
// "0.7.0-rc" -> "v0.7.0rc", "1.2.3" -> "v1.2.3"
const webVersion = `v${String(pkg.version).replace(/-/g, '')}`;

const target = path.join(__dirname, '..', 'src', 'app', 'build-info.ts');
const content =
    '// Auto-generated by scripts/set-build-version.js (do not edit by hand).\n' +
    "// WEB_VERSION comes from the 'version' field in package.json.\n" +
    '// BUILD_VERSION is stamped with the build time on every `ng build` so the\n' +
    '// player UI can show which build is running (lets you verify the latest\n' +
    '// deploy actually loaded).\n' +
    `export const WEB_VERSION = '${webVersion}';\n` +
    `export const BUILD_VERSION = '${stamp}';\n`;

fs.writeFileSync(target, content);
console.log('Web version:', webVersion);
console.log('Build version:', stamp);