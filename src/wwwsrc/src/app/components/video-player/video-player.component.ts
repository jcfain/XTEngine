  skipToMoneyShot(): void {
    const playing = this.videoService.playingMediaItem;
    if (playing) {
      const moneyShotSecs = (playing as any).metaData?.moneyShotSecs;
      if (moneyShotSecs && moneyShotSecs > 0) {
        this.onSeek(moneyShotSecs);
      }
    }
  }

