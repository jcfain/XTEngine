import { Component, OnInit, OnDestroy, ChangeDetectionStrategy } from '@angular/core';
import { DomSanitizer, SafeHtml } from '@angular/platform-browser';

import { Subscription } from 'rxjs';
import { VideoService } from '../../services/video.service';
import { MediaItem } from '../../models/interfaces';
import { WebsocketService } from '../../services/websocket.service';
import { MessageHandlerService } from '../../services/message-handler.service';
import { LocalSettingsService } from '../../services/local-settings.service';
import { MediaItemPropertiesComponent } from '../media-item-properties/media-item-properties.component';
import { MediaItemAltScriptsComponent } from '../media-item-alt-scripts/media-item-alt-scripts.component';
import { ScriptStatusComponent } from '../script-status/script-status.component';
import { MotionProfilesComponent } from '../motion-profiles/motion-profiles.component';

// Compact stand-in for the video player while media plays on the external
// player (see the "External player" local setting). It shows the playing
// item's name and heat map plus the player controls that do not drive the
// media player directly (play/pause, seek, volume, rate, prev/next and
// full screen are all absent).
@Component({
    selector: 'app-external-player',
    imports: [MediaItemPropertiesComponent, MediaItemAltScriptsComponent, ScriptStatusComponent, MotionProfilesComponent],
    templateUrl: './external-player.component.html',
    changeDetection: ChangeDetectionStrategy.Eager,
    styleUrl: './external-player.component.css'
})
export class ExternalPlayerComponent implements OnInit, OnDestroy {
    get playerVisible(): boolean {
        return this.mediaItem != null;
    }
    mediaItem: MediaItem | null = null;
    scriptStatusOpen = false;
    motionProfilesOpen = false;
    mediaSettingsOpen = false;
    altScriptsOpen = false;
    heatmapSvg: string | null = null;
    // The heat map SVG is generated by the XTEngine server (trusted). It must
    // be marked safe because the HTML sanitizer only whitelists HTML elements
    // and would strip the svg/rect/path tags.
    heatmapSvgSafe: SafeHtml | null = null;
    disableHeatmap = false;
    get showHeatmap(): boolean {
        return !this.disableHeatmap && this.heatmapSvg !== null;
    }

    private subscriptions: Subscription[] = [];

    constructor(
        private localSettingsService: LocalSettingsService,
        private webSocketService: WebsocketService,
        private messageHandlerService: MessageHandlerService,
        private videoService: VideoService,
        private sanitizer: DomSanitizer
    ) {
        this.subscriptions.push(
            this.messageHandlerService.stopAllMedia$.subscribe(() => {
                this.stop();
            })
        );
    }

    ngOnInit(): void {
        this.subscriptions.push(
            this.videoService.playingMediaItem$.subscribe(v => {
                const previous = this.mediaItem;
                this.mediaItem = v;
                // Only drop the heat map when a *different* video starts (or
                // none). The playing item is re-emitted on metadata updates
                // for the same item, and those must not wipe a heat map that
                // just arrived.
                if (!v || !previous || v.id !== previous.id) {
                    this.setHeatmapSvg(null);
                }
            }),
            this.localSettingsService.disableHeatmap$.subscribe(v => this.disableHeatmap = v),
            this.messageHandlerService.heatmap$.subscribe(v => this.setHeatmapSvg(v))
        );
    }

    ngOnDestroy(): void {
        this.subscriptions.forEach(s => s.unsubscribe());
    }

    setHeatmapSvg(svg: string | null): void {
        this.heatmapSvg = svg;
        this.heatmapSvgSafe = svg ? this.sanitizer.bypassSecurityTrustHtml(svg) : null;
    }

    // Hidden in the template for now (they need seeking in the external
    // player, which doesn't work yet) - kept for when it does.
    onSkipToNextAction(): void {
        this.webSocketService.sendSkipToNextAction();
    }

    onSkipToMoneyShot(): void {
        this.webSocketService.sendSkipToMoneyShot();
    }

    // The script status is rendered under the button row inside the player
    // container (see .script-status-embedded) - it just toggles its
    // visibility here.
    toggleScriptStatus(): void {
        this.scriptStatusOpen = !this.scriptStatusOpen;
    }

    // The motion profiles are rendered under the script status inside the
    // player container (see .motion-profiles-embedded) - it just toggles its
    // visibility here.
    toggleMotionProfiles(): void {
        this.motionProfilesOpen = !this.motionProfilesOpen;
    }

    openMediaSettings(): void {
        if (!this.mediaItem) {
            return;
        }
        this.mediaSettingsOpen = true;
    }

    closeMediaSettings(): void {
        this.mediaSettingsOpen = false;
    }

    openAltScripts(): void {
        if (!this.mediaItem) {
            return;
        }
        this.altScriptsOpen = true;
    }

    closeAltScripts(): void {
        this.altScriptsOpen = false;
    }

    stop(): void {
        if (this.scriptStatusOpen)
            this.toggleScriptStatus();
        if (this.motionProfilesOpen)
            this.toggleMotionProfiles();
        this.setHeatmapSvg(null);
        this.videoService.stopVideo();
    }
}